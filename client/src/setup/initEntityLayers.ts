/**
 * Runtime initialization of the chemrooms Cesium entity layers.
 *
 * This module runs after the room shell has loaded all parquet data
 * sources. It runs in two phases:
 *
 * Phase 1 (initEntityLayers, called when data is available):
 *   1. Loads the geoid grid (if available) and registers a SQL macro
 *      `geoid_offset(lon, lat)` that does bilinear interpolation.
 *      If the geoid file is missing, the macro is registered as a
 *      no-op (returns 0).
 *   2. Inspects the locations table for elevation-bearing columns,
 *      checking [elevation, z, measuring_pt] in priority order.
 *   3. Creates an empty `location_elevations_sampled` table that the
 *      layer SQL joins against. Rows are added in Phase 2 below.
 *   4. Returns the SQL strings for the locations + subsurface-samples
 *      Cesium entity layers, and the list of locations needing terrain
 *      sampling (i.e., where the data has no elevation).
 *
 * Phase 2 (sampleMissingElevations, called when the Cesium viewer is
 * ready):
 *   For each location with no surveyed elevation, sample
 *   `viewer.terrainProvider` to get the ellipsoidal terrain height,
 *   then INSERT (location_id, height_m) into location_elevations_sampled
 *   in DuckDB. The entity layer SQL is then re-fired so the new heights
 *   are picked up.
 *
 * Altitude resolution priority (per location):
 *   1. COALESCE(elevation, z, measuring_pt) — assumed NAVD88, geoid
 *      offset is added to convert to ellipsoidal.
 *   2. terrain-sampled height — already ellipsoidal, no offset added.
 *   3. 0 (last-resort fallback so points still render somewhere)
 *
 * Subsurface samples inherit their parent location's resolved height,
 * then subtract `depth_m`. A sample whose parent has no surveyed
 * elevation falls back to (terrain - depth), which is the right
 * behavior for ad-hoc data.
 *
 * The static cesium config in store.ts intentionally has *no* entity
 * layers so we don't see a flash of incorrectly-positioned points
 * before this setup runs.
 */

import type {DuckDbConnector} from '@sqlrooms/duckdb';
import {ARII_MANIFEST_URL, DATA_BASE_URL} from '../config';
import chemroomsCatalogsSql from '../sql/chemrooms_catalogs.sql?raw';
import {openAriiResults, type AriiSourceInfo} from './ariiSource';
import {buildSamplesLayerSql, SAMPLE_ENTITY_LIMIT} from './buildSamplesLayerSql';

const BASE_URL = import.meta.env.BASE_URL;
const GEOID_URL = `${BASE_URL}geoid/local.json`;
// The ChemDuck SQL is fetched from the data folder, beside the parquet it
// describes. It used to be fetched from the app's own origin
// (`${BASE_URL}data/sql/`), which only worked when CI copied server/data
// into the site; in local dev the request fell through to index.html and
// the schema silently failed to load.
// 00_bootstrap.sql (generated by chemduck from 01_tables.sql) creates the
// ChemDuck tables a project does not ship, empty, so every view can bind.
const CHEMDUCK_BOOTSTRAP_URL = `${DATA_BASE_URL}/sql/00_bootstrap.sql`;
const CHEMDUCK_MACROS_URL = `${DATA_BASE_URL}/sql/02_macros.sql`;
const CHEMDUCK_VIEWS_URL = `${DATA_BASE_URL}/sql/03_views.sql`;
// 08_aggregate_results.sql defines the high-level aggregate_results table
// macro the UI calls. It loads AFTER views since it references
// v_results_denormalized in its body. The aggregation_rules catalog that
// 07_catalogs.sql defines arrives as aggregation_rules.parquet, written by
// chemduck's bundle (server/sync_chemduck.py, or arii_hybrid.py publish).
const CHEMDUCK_AGG_RESULTS_URL = `${DATA_BASE_URL}/sql/08_aggregate_results.sql`;

/** Columns to check on the locations table for an elevation source. */
const ELEVATION_COLUMN_CANDIDATES = ['elevation', 'z', 'measuring_pt'];

/**
 * Inspect a table's columns and return which of the candidate names exist
 * (in their original priority order).
 */
async function detectColumns(
  connector: DuckDbConnector,
  tableName: string,
  candidates: string[],
): Promise<string[]> {
  const candList = candidates.map((c) => `'${c}'`).join(', ');
  const result = await connector.query(`
    SELECT column_name
    FROM information_schema.columns
    WHERE table_name = '${tableName}'
      AND column_name IN (${candList})
  `);
  const found = new Set<string>();
  for (const row of result.toArray()) {
    found.add((row as any).column_name);
  }
  return candidates.filter((c) => found.has(c));
}

/**
 * Try to load the geoid grid into a DuckDB table. Returns true if loaded,
 * false if the file isn't reachable.
 *
 * DuckDB-WASM doesn't have the httpfs extension loaded by default, so
 * `read_json('https://...')` or relative URLs fail. Instead, we fetch
 * the JSON via the browser's fetch API, create the table with DDL,
 * then bulk-INSERT the rows.
 */
async function tryLoadGeoidGrid(connector: DuckDbConnector): Promise<boolean> {
  let rows: Array<{
    row_idx: number;
    col_idx: number;
    lon: number;
    lat: number;
    offset_m: number;
  }>;
  try {
    const resp = await fetch(GEOID_URL);
    if (!resp.ok) return false;
    rows = await resp.json();
    if (!Array.isArray(rows) || rows.length === 0) return false;
  } catch {
    return false;
  }

  try {
    await connector.query(`
      CREATE OR REPLACE TABLE geoid_grid (
        row_idx INTEGER,
        col_idx INTEGER,
        lon DOUBLE,
        lat DOUBLE,
        offset_m DOUBLE
      )
    `);
    // Bulk insert — small dataset so a single VALUES clause is fine.
    const valuesSql = rows
      .map(
        (r) =>
          `(${r.row_idx}, ${r.col_idx}, ${r.lon}, ${r.lat}, ${r.offset_m})`,
      )
      .join(',\n');
    await connector.query(
      `INSERT INTO geoid_grid (row_idx, col_idx, lon, lat, offset_m) VALUES ${valuesSql}`,
    );
    return true;
  } catch (e) {
    console.warn('[init] failed to load geoid grid:', e);
    return false;
  }
}

/**
 * Register the `geoid_offset(lon, lat)` SQL macro. If `hasGrid` is false,
 * the macro is a no-op that returns 0 — so call sites don't have to know
 * whether a geoid file is present.
 */
async function registerGeoidMacro(
  connector: DuckDbConnector,
  hasGrid: boolean,
): Promise<void> {
  if (!hasGrid) {
    await connector.query(`
      CREATE OR REPLACE MACRO geoid_offset(qlon, qlat) AS (0.0)
    `);
    return;
  }

  await connector.query(`
    CREATE OR REPLACE MACRO geoid_offset(qlon, qlat) AS (
      WITH g AS (
        SELECT
          MIN(lon) AS west, MAX(lon) AS east,
          MIN(lat) AS south, MAX(lat) AS north,
          MAX(col_idx) + 1 AS nx,
          MAX(row_idx) + 1 AS ny
        FROM geoid_grid
      ),
      norm AS (
        SELECT
          GREATEST(0.0, LEAST(g.nx - 1.0001,
            (qlon - g.west) / NULLIF((g.east - g.west) / NULLIF(g.nx - 1, 0), 0)
          )) AS fx,
          GREATEST(0.0, LEAST(g.ny - 1.0001,
            (qlat - g.south) / NULLIF((g.north - g.south) / NULLIF(g.ny - 1, 0), 0)
          )) AS fy
        FROM g
      ),
      cells AS (
        SELECT
          CAST(FLOOR(fx) AS INTEGER) AS x0,
          CAST(FLOOR(fy) AS INTEGER) AS y0,
          fx - FLOOR(fx) AS u,
          fy - FLOOR(fy) AS v
        FROM norm
      )
      SELECT
          (1 - u) * (1 - v) * (SELECT offset_m FROM geoid_grid WHERE col_idx = c.x0     AND row_idx = c.y0)
        + u       * (1 - v) * (SELECT offset_m FROM geoid_grid WHERE col_idx = c.x0 + 1 AND row_idx = c.y0)
        + (1 - u) * v       * (SELECT offset_m FROM geoid_grid WHERE col_idx = c.x0     AND row_idx = c.y0 + 1)
        + u       * v       * (SELECT offset_m FROM geoid_grid WHERE col_idx = c.x0 + 1 AND row_idx = c.y0 + 1)
      FROM cells c
    )
  `);
}

/**
 * Load the ChemDuck macros + views into DuckDB-WASM.
 *
 * The chemduck schema has a real circular dependency between the macro
 * file and the views file:
 *   - `v_results_denormalized` references `make_dup_id` and `dv_qualifier`
 *     (defined in macros) at view-definition time
 *   - Four macros (`pivot_results_by_analyte`, `analyte_pair_data`,
 *     `analyte_composition`, `classify_concentration`) reference
 *     `v_results_denormalized` in their body, which newer DuckDB
 *     validates at macro-definition time
 *
 * The working load order is a three-pass bootstrap:
 *   1. Try macros → fails partway through but defines the simple ones
 *   2. Load views → succeeds because the simple macros are available
 *   3. Retry macros → now succeeds because views exist
 *
 * Returns `true` on success, `false` if the SQL files couldn't be fetched
 * (in which case the client falls back to base-table-only queries).
 */
async function loadChemduckSchema(
  connector: DuckDbConnector,
): Promise<boolean> {
  let bootstrapSql: string;
  let macrosSql: string;
  let viewsSql: string;
  let aggResultsSql: string;
  try {
    const [br, mr, vr, ar] = await Promise.all([
      fetch(CHEMDUCK_BOOTSTRAP_URL),
      fetch(CHEMDUCK_MACROS_URL),
      fetch(CHEMDUCK_VIEWS_URL),
      fetch(CHEMDUCK_AGG_RESULTS_URL),
    ]);
    if (!br.ok || !mr.ok || !vr.ok || !ar.ok) {
      console.error(
        '[init] ChemDuck SQL missing from the data folder ' +
          '(run server/sync_chemduck.py):',
        [br, mr, vr, ar].filter((r) => !r.ok).map((r) => r.url),
      );
      return false;
    }
    bootstrapSql = await br.text();
    macrosSql = await mr.text();
    viewsSql = await vr.text();
    aggResultsSql = await ar.text();
  } catch {
    return false;
  }

  // Pass 0: tables the project does not ship (screening_levels for an ARII
  // source, matrix_classes, ...), created empty. IF NOT EXISTS leaves the
  // project's own tables, and an ARII `results` view, alone.
  try {
    await connector.query(bootstrapSql);
  } catch (e) {
    console.error('[init] chemduck bootstrap failed:', e);
    return false;
  }

  // Pass 1: macros (partial — ignore the circular-reference error)
  try {
    await connector.query(macrosSql);
  } catch {
    // expected to fail at the first view-dependent macro; the simple
    // ones that precede it still get defined
  }

  // Pass 2: views (needs the simple macros from pass 1)
  try {
    await connector.query(viewsSql);
  } catch (e) {
    console.error('[init] chemduck views failed to load:', e);
    return false;
  }

  // Pass 3: macros again (now the views exist, so the view-dependent
  // macros can define themselves)
  try {
    await connector.query(macrosSql);
  } catch (e) {
    console.warn(
      '[init] chemduck macros retry had errors (views still work):',
      e,
    );
  }

  // Pass 4: the aggregate_results high-level table macro. It references
  // v_results_denormalized in its body and must load after the views.
  try {
    await connector.query(aggResultsSql);
  } catch (e) {
    console.error('[init] aggregate_results macro failed to load:', e);
    return false;
  }

  // Pass 5: chemrooms' catalogs (analyte_catalog, location_analytes). An
  // ARII source ships them as sidecar tables, because building them here
  // would scan every remote result; otherwise they are live views.
  try {
    const provided = await connector.query(`
      SELECT count(*) AS n FROM information_schema.tables
      WHERE table_name IN ('analyte_catalog', 'location_analytes')
    `);
    if (Number(provided.toArray()[0]?.n ?? 0) < 2) {
      await connector.query(chemroomsCatalogsSql);
    }
  } catch (e) {
    console.error('[init] chemrooms catalogs failed to load:', e);
    return false;
  }

  return true;
}

/**
 * Metres per depth unit. Must match DEPTH_UNIT_TO_M in chemduck's
 * tools/arii_hybrid.py, which refuses to publish any other unit.
 */
const DEPTH_UNIT_TO_M_SQL = `
  CREATE OR REPLACE MACRO depth_unit_to_m(u) AS (
    CASE lower(trim(u))
      WHEN 'm' THEN 1.0 WHEN 'meter' THEN 1.0 WHEN 'meters' THEN 1.0
      WHEN 'metre' THEN 1.0 WHEN 'metres' THEN 1.0
      WHEN 'cm' THEN 0.01 WHEN 'mm' THEN 0.001
      WHEN 'ft' THEN 0.3048 WHEN 'feet' THEN 0.3048 WHEN 'foot' THEN 0.3048
      WHEN 'in' THEN 0.0254 WHEN 'inch' THEN 0.0254 WHEN 'inches' THEN 0.0254
      ELSE NULL
    END
  )
`;

/**
 * `depth_interval_units`: the metres factor for each depth interval the
 * aggregate layer can produce, keyed as aggregate_results keys it
 * (location, matrix, top and bottom depth with NULL as 0).
 *
 * Depth used to be multiplied by 0.3048 everywhere. That is right for the
 * demo data (all `ft`) and wrong for EQuIS facilities reporting `m` or
 * `cm`. The values are converted at render time and never rewritten in
 * `samples`, because aggregate_results partitions on them. An interval
 * whose samples disagree on the unit, or name one not listed above, gets
 * no factor: it renders at the surface, and the count is logged.
 */
async function createDepthUnits(connector: DuckDbConnector): Promise<void> {
  await connector.query(DEPTH_UNIT_TO_M_SQL);
  await connector.query(`
    CREATE OR REPLACE TABLE depth_interval_units AS
    SELECT
      location_id,
      matrix,
      COALESCE(top_depth, 0) AS top_depth,
      COALESCE(bottom_depth, 0) AS bottom_depth,
      CASE WHEN count(DISTINCT lower(trim(depth_units))) = 1
        THEN min(depth_units) END AS depth_units,
      CASE WHEN count(DISTINCT lower(trim(depth_units))) = 1
        THEN depth_unit_to_m(min(depth_units)) END AS to_m
    FROM samples
    GROUP BY 1, 2, 3, 4
  `);
  const unknown = await connector.query(`
    SELECT count(*) AS n, list(DISTINCT depth_units) AS units
    FROM depth_interval_units
    WHERE to_m IS NULL AND (top_depth <> 0 OR bottom_depth <> 0)
  `);
  const row = unknown.toArray()[0] as {n?: number; units?: unknown} | undefined;
  if (row && Number(row.n) > 0) {
    console.warn(
      `[init] ${row.n} depth interval(s) have an unknown or mixed depth unit ` +
        'and render at the surface:',
      row.units,
    );
  }
}

/** SQL expression for the surveyed NAVD88 elevation, or NULL if none. */
function surveyedElevExpr(elevationColumns: string[], prefix = ''): string {
  if (elevationColumns.length === 0) return 'CAST(NULL AS DOUBLE)';
  const cols = elevationColumns.map((c) => `${prefix}${c}`);
  return `COALESCE(${cols.join(', ')})`;
}

export interface LocationToSample {
  location_id: string;
  longitude: number;
  latitude: number;
}

export type SourceInfo = {kind: 'chemduck'} | AriiSourceInfo;

export interface InitResult {
  hasGeoid: boolean;
  hasChemduckSchema: boolean;
  /** Which kind of project this is, and for ARII, how fresh. */
  source: SourceInfo;
  /** Why the source could not be opened, shown to the user; null if it was. */
  sourceError: string | null;
  elevationColumns: string[];
  locationsSql: string;
  samplesSql: string;
  /** Group the no-analyte samples view into sampling points (large projects). */
  groupSamples: boolean;
  /** Locations whose elevation must be sampled from terrain in Phase 2. */
  locationsNeedingTerrain: LocationToSample[];
}

/**
 * Phase 1: register the geoid macro, detect elevation columns, create
 * the `location_elevations_sampled` table, and build the layer SQL.
 *
 * Returns the SQL plus the list of locations that still need a
 * terrain-sampled elevation.
 */
export async function initEntityLayers(
  connector: DuckDbConnector,
): Promise<InitResult> {
  const hasGeoid = await tryLoadGeoidGrid(connector);
  await registerGeoidMacro(connector, hasGeoid);

  // An ARII project's `results` is a view over remote partitions, and must
  // exist before the ChemDuck views bind to it. If it cannot be opened the
  // reason is shown, and locations and samples (sidecars) still render.
  let source: SourceInfo = {kind: 'chemduck'};
  let sourceError: string | null = null;
  if (ARII_MANIFEST_URL) {
    try {
      source = await openAriiResults(connector, {
        manifestUrl: ARII_MANIFEST_URL,
        dataBaseUrl: DATA_BASE_URL,
      });
    } catch (e) {
      sourceError = e instanceof Error ? e.message : String(e);
      console.error('[init] ARII source refused:', e);
    }
  }

  // Load the chemduck macros + views. If the SQL files aren't reachable,
  // fall through to base-table-only queries (locations and
  // subsurface-samples still render without them).
  const hasChemduckSchema =
    sourceError === null && (await loadChemduckSchema(connector));
  await createDepthUnits(connector);

  const elevationColumns = await detectColumns(
    connector,
    'locations',
    ELEVATION_COLUMN_CANDIDATES,
  );

  // Create the empty terrain-sample table the layer SQL joins against.
  // Heights here are ALREADY ellipsoidal (terrain providers return
  // ellipsoidal meters), so we do NOT add geoid_offset on lookup.
  await connector.query(`
    CREATE OR REPLACE TABLE location_elevations_sampled (
      location_id VARCHAR,
      ellipsoidal_height_m DOUBLE
    )
  `);

  // List of locations that need terrain sampling (those with no surveyed
  // elevation in any candidate column).
  const surveyedLoc = surveyedElevExpr(elevationColumns);
  // Locations without coordinates stay in the tables (an ARII sidecar
  // keeps them, counted, rather than inventing a position) but are not
  // drawn or terrain-sampled.
  const needSampleResult = await connector.query(`
    SELECT location_id, x AS longitude, y AS latitude
    FROM locations
    WHERE ${surveyedLoc} IS NULL AND x IS NOT NULL AND y IS NOT NULL
  `);
  const locationsNeedingTerrain: LocationToSample[] = needSampleResult
    .toArray()
    .map((r: any) => ({
      location_id: String(r.location_id),
      longitude: Number(r.longitude),
      latitude: Number(r.latitude),
    }));

  // Build layer SQL. Each location's altitude is resolved as:
  //   1. Surveyed NAVD88 elevation + geoid_offset (ellipsoidal)
  //   2. Terrain-sampled height (already ellipsoidal)
  //   3. 0 (last-resort)
  const locationsSql = `
    SELECT
      l.location_id,
      l.x AS longitude,
      l.y AS latitude,
      COALESCE(
        ${surveyedLoc} + geoid_offset(l.x, l.y),
        s.ellipsoidal_height_m,
        0.0
      ) AS altitude,
      l.loc_type,
      COALESCE(l.loc_desc, l.location_id) AS label
    FROM locations l
    LEFT JOIN location_elevations_sampled s
      ON s.location_id = l.location_id
    WHERE l.x IS NOT NULL AND l.y IS NOT NULL
  `;

  // Subsurface samples inherit the parent location's resolved height,
  // then subtract `depth` converted to metres by its depth_units. A sample
  // with no depth is treated as a surface sample (depth = 0), per the
  // project convention that a sample on a surveyed location with no depth
  // is at the location's elevation.
  //
  // The same query the samples layer uses with no analyte selected, so
  // depth units are handled in one place.
  const drawable = await connector.query(`
    SELECT count(*) AS n FROM samples s
    JOIN locations l ON l.location_id = s.location_id
    WHERE l.x IS NOT NULL AND l.y IS NOT NULL
  `);
  const groupSamples =
    Number(drawable.toArray()[0]?.n ?? 0) > SAMPLE_ENTITY_LIMIT;
  const samplesSql = buildSamplesLayerSql({
    elevationColumns,
    coloringAnalyte: null,
    eventAgg: '',
    dupAgg: '',
    ndMethod: '',
    matrixFilter: null,
    groupSamples,
  });

  return {
    hasGeoid,
    hasChemduckSchema,
    source,
    sourceError,
    elevationColumns,
    locationsSql,
    samplesSql,
    groupSamples,
    locationsNeedingTerrain,
  };
}

/**
 * Phase 2: insert terrain-sampled elevations into
 * `location_elevations_sampled`. Caller is responsible for triggering a
 * layer refetch afterward.
 *
 * Heights are written as ellipsoidal meters (whatever the terrain
 * provider returns), with no geoid offset applied.
 */
export async function writeSampledElevations(
  connector: DuckDbConnector,
  rows: Array<{location_id: string; ellipsoidal_height_m: number}>,
): Promise<void> {
  if (rows.length === 0) return;

  // Use a single VALUES clause for the bulk insert
  const valuesSql = rows
    .map(
      (r) =>
        `('${r.location_id.replace(/'/g, "''")}', ${r.ellipsoidal_height_m})`,
    )
    .join(', ');

  await connector.query(`
    INSERT INTO location_elevations_sampled (location_id, ellipsoidal_height_m)
    VALUES ${valuesSql}
  `);
}
